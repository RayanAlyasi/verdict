// Writes app/theme.css, Tailwind's theme, from docs/brand/tokens.json, the design tokens' one source.
// With --check (pnpm lint), it fails instead when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const TOKENS = new URL("../../../docs/brand/tokens.json", import.meta.url);
const THEME = new URL("../app/theme.css", import.meta.url);

export function themeCss(tokens) {
  const lines = [];
  const add = (name, value) => lines.push(`  --${name}: ${value};`);
  const group = (prefix, values) => {
    // Tailwind's stock scale goes first, so only brand values exist and none collide with them
    // (stock rounded-lg is 8px, the brand's is 16px).
    lines.push(`  --${prefix}-*: initial;`);
    for (const [name, value] of Object.entries(values)) add(`${prefix}-${name}`, value);
  };

  group("color", tokens.color.dark);
  // The light palette is for printed papers and the light theme; its names overlap the dark ones.
  for (const [name, value] of Object.entries(tokens.color.light)) add(`color-light-${name}`, value);

  group("radius", tokens.radius);
  group("shadow", tokens.shadow);
  group("breakpoint", tokens.breakpoints);
  for (const [name, value] of Object.entries(tokens.background)) {
    add(`background-image-${name}`, value);
  }

  // One spacing base, so Tailwind's numeric classes are the brand scale: p-1 is 4px, p-6 is 24px.
  const base = parseInt(tokens.spacing["space-1"], 10);
  for (const [name, value] of Object.entries(tokens.spacing)) {
    if (parseInt(value, 10) % base !== 0) throw new Error(`${name} isn't a multiple of ${base}px`);
  }
  add("spacing", `${base}px`);
  add("spacing-touch-target", tokens["touch-target-min"]);

  // next/font self-hosts Readex Pro and puts it in --font-readex-pro (app/[lang]/layout.tsx), with
  // Arial resized to its Latin letters as the fallback. Latin text barely moves when the font
  // arrives where Arial exists; Arabic text, and Android, which has no Arial, can still reflow.
  const family = tokens.type.family.replace(/^"Readex Pro"/, "var(--font-readex-pro)");
  if (family === tokens.type.family)
    throw new Error('type.family no longer starts with "Readex Pro"');
  add("font-sans", family);
  lines.push("  --text-*: initial;");
  for (const [name, style] of Object.entries(tokens.type.styles)) {
    add(`text-${name}`, style.size);
    add(`text-${name}--line-height`, style.lineHeight);
    add(`text-${name}--font-weight`, String(style.weight));
  }

  const { easing, stagger, ...durations } = tokens.motion;
  lines.push("  --ease-*: initial;");
  add("ease-standard", easing);
  for (const [name, value] of Object.entries(durations)) add(`transition-duration-${name}`, value);
  // A bare transition-colors uses these, so it follows the brand without a duration class.
  add("default-transition-duration", durations.base);
  add("default-transition-timing-function", easing);
  add("motion-stagger", stagger);

  return [
    "/* Generated by scripts/tokens.mjs from docs/brand/tokens.json. Edit the tokens, then run",
    "   pnpm --dir apps/web tokens. */",
    // static: every token stays a CSS variable even before a class uses it, for code such as the
    // globe's canvas that reads colours from CSS.
    "@theme static {",
    ...lines,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = themeCss(JSON.parse(readFileSync(TOKENS, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(THEME, "utf8") !== css) {
      console.error(
        "app/theme.css is out of date with docs/brand/tokens.json. Run pnpm --dir apps/web tokens.",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(THEME, css);
  }
}
